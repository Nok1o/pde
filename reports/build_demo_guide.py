def candidates(data):
    baseline = {
        r["target_pct"]: r for r in data["rows"] if r["method"] in ("lod", "lod_serial")
    }
    result = []
    for row in data["rows"]:
        base = baseline[row["target_pct"]]
        if (
            row["method"] in ("lod", "lod_serial")
            or not row["seconds"]
            or not base["seconds"]
        ):
            continue
        if row["seconds"] < base["seconds"]:
            result.append((row, base))
    return sorted(result, key=lambda pair: (pair[0]["target_pct"], pair[0]["seconds"]))


def confirmation(case_id, method, target):
    return next(
        r
        for r in CHECKS["comparisons"]
        if r["case"] == case_id and r["method"] == method and r["target_pct"] == target
    )


def wins(data):
    return [
        (r, b)
        for r, b in candidates(data)
        if confirmation(data["case"]["id"], r["method"], r["target_pct"])["confirmed"]
    ]


