def fmt(x, d=2):
    return "—" if x is None else f"{x:.{d}f}"


def params(r):
    if not r["parameters"]:
        return "—"
    q = r["parameters"]
    parts = []
    if "tol" in q:
        parts.append("tol=" + format(q["tol"], ".3g"))
    if "walks" in q:
        parts.append("N=" + str(q["walks"]))
    return ", ".join(parts)


def case_label(c):
    problem = (
        "α=" + str(c["alpha"]) if c["family"] == "nonlinear" else PRESETS[c["problem"]]
    )
    request = c.get("mode", "point")
    request = {"point": "точка", "patch": "участок 3×3", "field": "поле 15×15"}[request]
    dimension = 3 if c["family"] in ("3d", "mixed3d") else 2
    point = c.get("point", [c["n"] // 2] * dimension)
    if request == "точка":
        request += " " + str(tuple(point))
    return f"{c['id']} · {FAMILIES[c['family']]} · {problem} · n={c['n']} · {request}"


